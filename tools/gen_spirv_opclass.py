#!/usr/bin/env python3
# Writes server/spirv_opclass.inc from the SPIR-V core grammar (spirv-headers'
# spirv.core.grammar.json): which opcodes define a result id, and which also a result type.
#   tools/gen_spirv_opclass.py /usr/include/spirv/unified1/spirv.core.grammar.json > server/spirv_opclass.inc
import json, sys

g = json.load(open(sys.argv[1]))
cls = {}
for ins in g["instructions"]:
    kinds = [o["kind"] for o in ins.get("operands", [])]
    c = 2 if "IdResultType" in kinds else 1 if "IdResult" in kinds else 0
    cls.setdefault(ins["opcode"], c)
print("/* Generated by tools/gen_spirv_opclass.py from the SPIR-V core grammar %d.%d rev %d - do not edit. */"
      % (g["major_version"], g["minor_version"], g["revision"]))
print("/* 0: no result, 1: a result id only (w[0]), 2: a result type and id (w[0], w[1]); -1: not in the grammar */")
print("static int spv_op_class(uint32_t op)\n{\n    switch (op) {")
for c in (0, 1):
    ops = sorted(o for o, k in cls.items() if k == c)
    for i in range(0, len(ops), 12):
        print("    " + " ".join("case %d:" % o for o in ops[i:i + 12]))
    print("        return %d;" % c)
ops = sorted(o for o, k in cls.items() if k == 2)
for i in range(0, len(ops), 12):
    print("    " + " ".join("case %d:" % o for o in ops[i:i + 12]))
print("        return 2;\n    default:\n        return -1;\n    }\n}")
