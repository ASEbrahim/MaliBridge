#!/bin/bash
# Compiles the polygon-mode emulation's compute shader (server_emu_polygon.c) into
# server/polygon_spv.h (committed, so a build needs no shader compiler). Needs glslc (GLSLC=...,
# else the Android NDK's).
set -eu
cd "$(dirname "$0")"
glslc=${GLSLC:-$(ls "${ANDROID_HOME:-$HOME/Android/Sdk}"/ndk/*/shader-tools/*/glslc 2>/dev/null | tail -1)}
[ -x "$glslc" ] || { echo "no glslc (set GLSLC)" >&2; exit 1; }
out=../../polygon_spv.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
"$glslc" -O --target-env=vulkan1.0 -fshader-stage=comp -mfmt=num -o "$tmp/lines.inc" lines.comp
{
  echo "/* Generated by server/shaders/polygon/build_polygon.sh from lines.comp - do not edit. */"
  echo "#pragma once"
  echo "#include <stdint.h>"
  echo "static const uint32_t spv_polygon_lines[] = {"
  cat "$tmp/lines.inc"
  echo "};"
} > "$out"
