#!/bin/bash
# Compiles the startup probe's shaders (server_probe.c) into server/probe_spv.h (committed, so a
# build needs no shader compiler). Needs glslc (GLSLC=..., else the Android NDK's).
set -eu
cd "$(dirname "$0")"
python3 gen_aces.py
glslc=${GLSLC:-$(ls "${ANDROID_HOME:-$HOME/Android/Sdk}"/ndk/*/shader-tools/*/glslc 2>/dev/null | tail -1)}
[ -x "$glslc" ] || { echo "no glslc (set GLSLC)" >&2; exit 1; }
out=../../probe_spv.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
echo "/* Generated by server/shaders/probe/build_probe.sh - do not edit. */" > "$out"
echo "#pragma once" >> "$out"
echo "#include <stdint.h>" >> "$out"
# name, file, env, extra flags
shader() {
  local name=$1 file=$2 env=$3; shift 3
  "$glslc" --target-env="$env" "$@" -o "$tmp/$name.spv" "$file"
  if [ "$name" = bitwise ]; then
    # MK-03's pattern must reach the driver: a vector bitwise op (and a shift) fed by an
    # OpVectorShuffle and by an OpCompositeConstruct (built with -O0, nothing folded)
    local dis=${SPIRV_DIS:-$(dirname "$glslc")/spirv-dis}
    [ -x "$dis" ] || dis=spirv-dis
    "$dis" "$tmp/$name.spv" > "$tmp/$name.txt"
    for op in OpVectorShuffle OpCompositeConstruct OpBitwiseOr OpBitwiseAnd OpBitwiseXor OpNot OpShiftRightArithmetic OpShiftLeftLogical; do
      grep -q "$op" "$tmp/$name.txt" || { echo "bitwise.comp: no $op left in the SPIR-V" >&2; exit 1; }
    done
  fi
  if [ "$name" = spec ]; then
    # DXVK's form: the composite of specialization constants declared OpConstantComposite (44)
    # instead of OpSpecConstantComposite (51) - what server_spvfix.c undoes for the driver.
    python3 - "$tmp/$name.spv" <<'PY'
import struct, sys
p = sys.argv[1]
w = list(struct.unpack("<%dI" % (len(open(p, "rb").read()) // 4), open(p, "rb").read()))
i, n = 5, 0
while i < len(w):
    op, wc = w[i] & 0xffff, w[i] >> 16
    if op == 51:
        w[i] = (wc << 16) | 44
        n += 1
    i += wc
assert n == 1, n
open(p, "wb").write(struct.pack("<%dI" % len(w), *w))
PY
  fi
  python3 - "$tmp/$name.spv" "spv_probe_$name" >> "$out" <<'PY'
import struct, sys
b = open(sys.argv[1], "rb").read()
w = struct.unpack("<%dI" % (len(b) // 4), b)
print("static const uint32_t %s[] = {" % sys.argv[2])
for i in range(0, len(w), 8):
    print("    " + ", ".join("0x%08x" % x for x in w[i:i + 8]) + ",")
print("};")
PY
}
shader vid vid.vert vulkan1.0
shader inst inst.vert vulkan1.0
shader clip clip.vert vulkan1.0
shader layer_vs layer.vert vulkan1.2
shader layer_gs layer.geom vulkan1.0
shader col col.frag vulkan1.0
shader push push.comp vulkan1.0
shader null null.comp vulkan1.0
shader tex tex.comp vulkan1.0
shader spec spec.comp vulkan1.0 -O
shader aces aces.frag vulkan1.0
shader quad quad.vert vulkan1.0
shader quad_vp quad_vp.vert vulkan1.2
shader face face.frag vulkan1.0
shader vbs vbs.vert vulkan1.0
shader bitwise bitwise.comp vulkan1.0 -O0
echo "wrote $out"
