#!/usr/bin/env python3
"""devclamp_table.h from vk.xml: every struct that may extend VkDeviceCreateInfo (sType, size,
whether it is a feature struct and its VkBool32 members), for the structs vulkan_core.h defines.
    gen_devclamp_table.py <vk.xml> <vulkan_core.h> <out.h>"""
import re, sys
import xml.etree.ElementTree as ET
xml, core, out = sys.argv[1:4]
src = open(core).read()
defined = set(re.findall(r"typedef struct (Vk\w+) \{", src))
enums = set(re.findall(r"^\s+(VK_STRUCTURE_TYPE_\w+) = ", src, re.M))
reg = ET.parse(xml).getroot()
rows = []
for t in reg.find("types").findall("type"):
    if t.get("category") != "struct" or t.get("alias"): continue
    name = t.get("name")
    ext = (t.get("structextends") or "").split(",")
    if "VkDeviceCreateInfo" not in ext or name not in defined: continue
    if "vulkansc" == t.get("api"): continue
    stype, bools, other = None, [], False
    for m in t.findall("member"):
        if m.get("api") == "vulkansc": continue
        mt, mn = m.find("type").text, m.find("name").text
        if mn == "sType": stype = m.get("values"); continue
        if mn == "pNext": continue
        if mt == "VkBool32" and "[" not in "".join(m.itertext()): bools.append(mn)
        else: other = True
    feat = "VkPhysicalDeviceFeatures2" in ext and not other and bools
    if stype in enums: rows.append((stype, name, bool(feat), bools if feat else []))
with open(out, "w") as f:
    f.write("/* generated by gen_devclamp_table.py from vk.xml; do not edit */\n")
    f.write("static const struct dc_struct { VkStructureType stype; size_t size; const char *name; int feature; const char *bools; } dc_structs[] = {\n")
    for stype, name, feat, bools in rows:
        f.write(f'    {{{stype}, sizeof({name}), "{name}", {int(feat)}, "{",".join(bools)}"}},\n')
    f.write("};\n")
print(f"{out}: {len(rows)} structs, {sum(r[2] for r in rows)} feature structs")
