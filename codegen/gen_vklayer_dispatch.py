"""
Generates layer_dispatch_gen.h
"""

import os
import re
import sys
from cached_server_hook_list import CACHED_SERVER_HOOKS
from collections import defaultdict
from gen_server_hook_list import get_server_hooks, cache_server_hooks
import xml.etree.ElementTree as ET

if CACHED_SERVER_HOOKS != get_server_hooks():
    old_hooks = CACHED_SERVER_HOOKS
    print("Cached hooks are outdated (new hooks are implemented in MaliBridge), updating them now")
    CACHED_SERVER_HOOKS = cache_server_hooks()
    print("New hooks:")
    for hook in sorted(set(CACHED_SERVER_HOOKS) - set(old_hooks)):
        print("  + ", hook)

    print("Removed hooks:")
    for hook in sorted(set(old_hooks) - set(CACHED_SERVER_HOOKS)):
        print("  - ", hook)


MANUAL_COMMANDS = {
    "vkCreateInstance", "vkDestroyInstance",
    "vkCreateDevice", "vkDestroyDevice",
    "vkGetInstanceProcAddr", "vkGetDeviceProcAddr",
    "vkEnumerateInstanceExtensionProperties", "vkEnumerateInstanceLayerProperties",
    "vkEnumerateDeviceExtensionProperties", "vkEnumerateDeviceLayerProperties",
    "vkGetPhysicalDeviceFeatures", "vkGetPhysicalDeviceFeatures2",
    "vkGetPhysicalDeviceProperties", "vkGetPhysicalDeviceProperties2",
    "vkGetPhysicalDeviceFormatProperties", "vkGetPhysicalDeviceFormatProperties2",
    "vkGetPhysicalDeviceMemoryProperties", "vkGetPhysicalDeviceMemoryProperties2",
    "vkEnumeratePhysicalDevices", "vkEnumeratePhysicalDeviceGroups"
}

HANDLE_CREATION_COMMANDS = {
    "vkAllocateCommandBuffers", "vkFreeCommandBuffers",
    "vkGetDeviceQueue", "vkGetDeviceQueue2"
}

DISPATCHABLE_TYPES = {"VkInstance", "VkPhysicalDevice", "VkDevice", "VkQueue", "VkCommandBuffer"}

# API, hook, file
LAYER_FUNCTIONS = sorted({api for api, _, _ in CACHED_SERVER_HOOKS})

def parse_vk_xml(xml_path):
    tree = ET.parse(xml_path)
    root = tree.getroot()
    commands = {}
    aliases = {}

    for cmd_node in root.findall(".//commands/command"):
        name = cmd_node.get("name")
        alias = cmd_node.get("alias")
        if alias and name:
            aliases[name] = alias
            continue

        proto = cmd_node.find("proto")
        if proto is None: continue
        cmd_name = proto.find("name").text
        ret_type = "".join(proto.itertext()).replace(cmd_name, "").strip()

        params = []
        for param in cmd_node.findall("param"):
            p_name = param.find("name").text
            p_type_full = "".join(param.itertext()).strip()
            p_type_elem = param.find("type")
            p_raw_type = p_type_elem.text if p_type_elem is not None else ""
            params.append({"name": p_name, "decl": p_type_full, "type": p_raw_type})

        commands[cmd_name] = {
            "name": cmd_name, "return": ret_type, "params": params,
            "first_type": params[0]["type"] if params else ""
        }

    for alias_name, target in aliases.items():
        while target in aliases:
            target = aliases[target]
        if target in commands:
            cmd_data = dict(commands[target])
            cmd_data["name"] = alias_name
            cmd_data["primary_target"] = target
            commands[alias_name] = cmd_data

    return commands, aliases

def generate_header(commands, aliases, out_path):
    mali_bridge_hooks  = defaultdict(list)
    for api, hook, file in CACHED_SERVER_HOOKS:
        mali_bridge_hooks[api].append(f"{file} ({hook})")

    lines = []
    lines.append("/* Generated by codegen/gen_layer_dispatch.py - DO NOT EDIT. */")
    lines.append("#ifndef VKB_LAYER_DISPATCH_GEN_H")
    lines.append("#define VKB_LAYER_DISPATCH_GEN_H")
    lines.append("")
    lines.append("#include <vulkan/vulkan.h>")
    lines.append("")
    lines.append("PFN_vkVoidFunction layer_lookup_device_proc(const char *pName);")
    lines.append("PFN_vkVoidFunction layer_lookup_instance_proc(const char *pName);")
    lines.append("")

    dev_proc_list = list(HANDLE_CREATION_COMMANDS)
    inst_proc_list = []

    for name in sorted(HANDLE_CREATION_COMMANDS | MANUAL_COMMANDS):
        cmd = commands[name]
        ret = cmd["return"]
        param_decls = ", ".join(re.sub(r'\s+', ' ', p["decl"]) for p in cmd["params"])
        func_code = f"VKAPI_ATTR {ret} VKAPI_CALL Layer_{name}({param_decls});"
        lines.append(func_code)

        first_type = cmd["first_type"]
        if first_type in {"VkDevice", "VkQueue", "VkCommandBuffer"}:
            dev_proc_list.append(name)
        else:
            inst_proc_list.append(name)

    lines.append("")
    lines.append("#endif // VKB_LAYER_DISPATCH_GEN_H")
    lines.append("")
    lines.append("#ifdef VKB_LAYER_GEN_IMPLEMENTATION")
    lines.append("#undef VKB_LAYER_GEN_IMPLEMENTATION")
    lines.append("")

    for name in sorted(LAYER_FUNCTIONS):
        if name in MANUAL_COMMANDS or name in HANDLE_CREATION_COMMANDS:
            continue
        if name not in commands:
            print(f"WARN: {name} is not a known Vulkan API")
            continue

        cmd = commands[name]

        first_type = cmd["first_type"]
        if first_type not in DISPATCHABLE_TYPES:
            print(f"WARN: {name}'s handle ({first_type}) is not a tracked dispatchable handle type.")
            continue

        if first_type in {"VkDevice", "VkQueue", "VkCommandBuffer"}:
            dev_proc_list.append(name)
        else:
            inst_proc_list.append(name)

        ret = cmd["return"]
        param_decls = ", ".join(re.sub(r'\s+', ' ', p["decl"]) for p in cmd["params"])
        param_names = ", ".join(re.sub(r'\s+', ' ', p["name"]) for p in cmd["params"])
        first_arg = cmd["params"][0]["name"]
        is_void = (ret == "void")

        func_code = f"static VKAPI_ATTR {ret} VKAPI_CALL Layer_{name}({param_decls})\n{{\n"
        for use in sorted(mali_bridge_hooks[name]):
            func_code += f"    // {use}\n"
        func_code += f"    auto ctx = get_scoped_ctx({first_arg});\n"
        call_stmt = f"ctx->t->dt.{name}({param_names});"
        if is_void:
            func_code += f"    {call_stmt}\n"
        else:
            func_code += f"    return {call_stmt}\n"
        func_code += "}\n"
        lines.append(func_code)


    expanded_dev_procs = {}
    for name in dev_proc_list:
        expanded_dev_procs[name] = name
        for alias_name, target in aliases.items():
            if target == name:
                expanded_dev_procs[alias_name] = name
            elif name == alias_name:
                expanded_dev_procs[target] = name

    lines.append("")

    lines.append("PFN_vkVoidFunction layer_lookup_device_proc(const char *pName)\n{")
    for name, target_impl in sorted(expanded_dev_procs.items()):
        lines.append(f'    if (strcmp(pName, "{name}") == 0) return reinterpret_cast<PFN_vkVoidFunction>(Layer_{target_impl});')
    lines.append("    return nullptr;\n}\n")

    lines.append("PFN_vkVoidFunction layer_lookup_instance_proc(const char *pName)\n{")
    for name in sorted(inst_proc_list):
        lines.append(f'    if (strcmp(pName, "{name}") == 0) return reinterpret_cast<PFN_vkVoidFunction>(Layer_{name});')
    lines.append("    return nullptr;\n}\n")

    lines.append("#endif // VKB_LAYER_GEN_IMPLEMENTATION\n")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Generated {out_path} ({len(dev_proc_list) + len(inst_proc_list)} commands)")

if __name__ == "__main__":
    script_dir = os.path.dirname(os.path.abspath(__file__))
    root_dir = os.path.abspath(os.path.join(script_dir, ".."))
    default_xml = os.path.join(root_dir, "third_party/Vulkan-Headers-1.4.341/registry/vk.xml")
    default_out = os.path.join(root_dir, "layer/gen/layer_dispatch_gen.h")

    xml_file = sys.argv[1] if len(sys.argv) > 1 else default_xml
    out_file = sys.argv[2] if len(sys.argv) > 2 else default_out

    if not os.path.exists(xml_file):
        print(f"Error: {xml_file} not found.", file=sys.stderr)
        sys.exit(1)

    cmds, aliases = parse_vk_xml(xml_file)
    generate_header(cmds, aliases, out_file)
