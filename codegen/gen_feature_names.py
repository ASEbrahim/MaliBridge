#!/usr/bin/env python3
"""server/feature_names.inc from vk.xml: every feature structure that may extend VkDeviceCreateInfo
(sType, size, name, its VkBool32 members, which are all its members, the extension that brings it and
the Vulkan version that made it core), for the structures vulkan_core.h defines. The server names
with it what a refused vkCreateDevice asked for that the driver lacks (server_emu.c,
vkb_emu_device_lacks), and the feature clamp checks its structures with it.
    gen_feature_names.py <vk.xml> <vulkan_core.h> <out.inc>"""
import re, sys
import xml.etree.ElementTree as ET

xml, core, out = sys.argv[1:4]
src = open(core).read()
defined = set(re.findall(r"typedef struct (Vk\w+) \{", src))
# sTypes outside any #ifdef but the header guard (the beta ones sit in VK_ENABLE_BETA_EXTENSIONS even
# in vulkan_core.h)
enums, depth = set(), 0
for line in src.splitlines():
    if line.startswith("#if"):
        depth += 1
    elif line.startswith("#endif"):
        depth -= 1
    m = re.match(r"\s+(VK_STRUCTURE_TYPE_\w+) = ", line)
    if m and depth == 1:
        enums.add(m.group(1))
reg = ET.parse(xml).getroot()
alias = {t.get("name"): t.get("alias") for t in reg.find("types").findall("type") if t.get("alias")}
core_ver, ext_of = {}, {}
for f in reg.findall("feature"):
    if "vulkan" not in (f.get("api") or "vulkan").split(","):
        continue
    m = re.match(r"VK_(?:BASE_|COMPUTE_|GRAPHICS_)?VERSION_(\d+)_(\d+)$", f.get("name"))
    if not m:
        continue
    for r in f.findall("require"):
        for t in r.findall("type"):
            n = alias.get(t.get("name"), t.get("name"))
            core_ver.setdefault(n, (int(m.group(1)), int(m.group(2))))
for e in reg.find("extensions").findall("extension"):
    if "vulkan" not in (e.get("supported") or "").split(","):
        continue
    for r in e.findall("require"):
        for t in r.findall("type"):
            ext_of.setdefault(alias.get(t.get("name"), t.get("name")), e.get("name"))
rows = []
for t in reg.find("types").findall("type"):
    if t.get("category") != "struct" or t.get("alias") or t.get("api") == "vulkansc":
        continue
    name = t.get("name")
    ext = (t.get("structextends") or "").split(",")
    if "VkDeviceCreateInfo" not in ext or "VkPhysicalDeviceFeatures2" not in ext or name not in defined:
        continue
    stype, bools, other = None, [], False
    for m in t.findall("member"):
        if m.get("api") == "vulkansc":
            continue
        mt, mn = m.find("type").text, m.find("name").text
        if mn == "sType":
            stype = m.get("values")
        elif mn == "pNext":
            pass
        elif mt == "VkBool32" and "[" not in "".join(m.itertext()):
            bools.append(mn)
        else:
            other = True
    if stype in enums and bools and not other:
        rows.append((stype, name, bools, ext_of.get(name), core_ver.get(name)))
rows.sort(key=lambda r: r[1])
with open(out, "w") as f:
    f.write("/* SPDX-License-Identifier: GPL-3.0-or-later\n *\n")
    f.write(" * Generated by codegen/gen_feature_names.py from vk.xml (Vulkan-Headers 1.4.341); do not edit.\n")
    f.write(" * Feature structures that may extend VkDeviceCreateInfo, each all VkBool32 members after the header.\n")
    f.write(" * FEAT(sType, structure, members, extension or NULL, Vulkan version that made it core or 0)\n */\n")
    for stype, name, bools, ext, ver in rows:
        e = f'"{ext}"' if ext else "NULL"
        v = f"VK_MAKE_API_VERSION(0, {ver[0]}, {ver[1]}, 0)" if ver else "0"
        f.write(f'FEAT({stype}, {name}, "{",".join(bools)}", {e}, {v})\n')
print(f"{out}: {len(rows)} feature structures")
