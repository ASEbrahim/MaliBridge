"""
Scans source files in server/ and extract every hook across:
 1. ERRATA_HOOK(t, vkFunc, hookFunc)
 2. HOOK(vkFunc, hookFunc, saved)
 3. t->dt.vkFunc = hookFunc / dt->vkFunc = hookFunc
 4. t->real.vkFunc = hookFunc / real->vkFunc = hookFunc
 5. Local table overrides (dt.vkFunc = hookFunc)
 6. Static/global array trampolines
"""

import sys
import os
import re

IGNORED_HOOK_TARGETS = {
    "NULL", "nullptr", "0", "fn", "mine", "saved", "field"
}

# ERRATA_HOOK(t, vkFunc, hookFunc)
RE_ERRATA_HOOK = re.compile(
    r'\bERRATA_HOOK\s*\(\s*[^,]+,\s*(vk[A-Za-z0-9_]+)\s*,\s*([A-Za-z0-9_]+)\s*\)'
)

# HOOK(vkFunc, hookFunc, saved) e.g. server_gpuprof.c
RE_GPU_PROF_HOOK = re.compile(
    r'(?<!UN)\bHOOK\s*\(\s*(vk[A-Za-z0-9_]+)\s*,\s*([A-Za-z0-9_]+)\s*,'
)

# Assignments to dt or real (e.g. t->dt.vkFoo = bar;, dt->vkFoo = bar;, dt.vkFoo = bar;)
RE_ASSIGNMENT_HOOK = re.compile(
    r'(?:(?:\b\w+->|\b\w+\.)(?:dt|real)\.|\bdt->|\bdt\.)(vk[A-Za-z0-9_]+)\s*=\s*([A-Za-z_][A-Za-z0-9_]*)\s*;'
)

RE_PATTERNS = (RE_ERRATA_HOOK, RE_GPU_PROF_HOOK, RE_ASSIGNMENT_HOOK)

def extract_hooks_from_file(file_path):
    filename = os.path.basename(file_path)
    hooks = set()

    with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
        content = f.read()

    for pattern in RE_PATTERNS:
        for match in pattern.finditer(content):
            vk_func, hook_func = match.groups()
            if hook_func not in IGNORED_HOOK_TARGETS:
                hooks.add((vk_func, hook_func, filename))

    return hooks

def get_server_hooks(server_dir=None):
    if not server_dir:
        script_dir = os.path.dirname(os.path.abspath(__file__))
        root_dir = os.path.abspath(os.path.join(script_dir, ".."))
        server_dir = os.path.join(root_dir, "server")

    all_hooks = set()

    for root, _, files in os.walk(server_dir):
        for file in files:
            if file.endswith((".c", ".cpp", ".h")):
                file_path = os.path.join(root, file)
                extracted = extract_hooks_from_file(file_path)
                all_hooks.update(extracted)

    return sorted(all_hooks, key=lambda item: (item[0], item[1], item[2]))


def cache_server_hooks(server_dir=None, out_path=None):
    script_dir = os.path.dirname(os.path.abspath(__file__))
    root_dir = os.path.abspath(os.path.join(script_dir, ".."))
    default_server_dir = os.path.join(root_dir, "server")
    default_out_file = os.path.join(script_dir, "cached_server_hook_list.py")

    server_dir = server_dir if server_dir else default_server_dir
    out_path = out_path if out_path else default_out_file

    if not os.path.isdir(server_dir):
        print(f"Error: directory '{server_dir}' not found.")
        sys.exit(1)

    sorted_hooks = get_server_hooks(server_dir)

    lines = [
        "# Auto-generated by tools/gen_server_hook_list.py - DO NOT EDIT.",
        "",
        "CACHED_SERVER_HOOKS = ["
    ]

    for vk_func, hook_func, file_name in sorted_hooks:
        lines.append(f'    ("{vk_func}", "{hook_func}", "{file_name}"),')

    lines.append("]\n")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    return sorted_hooks


def main():
    sorted_hooks = cache_server_hooks(sys.argv[1] if len(sys.argv) > 1 else None, sys.argv[2] if len(sys.argv) > 2 else None)
    print(f"Found {len(sorted_hooks)} hooks")

if __name__ == "__main__":
    main()
