#!/usr/bin/env python3
"""Writes layer/tests/fake_driver_names.cpp: the Vulkan functions the fake driver is asked for and
does not implement, and that are known to be harmless.

Ensure you buld build-linux-x86-64/layer/tests/layer_tests via

    bash scripts/build-linux-x86-64.sh
"""

import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TESTS = os.path.join(ROOT, "build-linux-x86-64/layer/tests/layer_tests")
OUT = os.path.join(HERE, "fake_driver_names.cpp")

HEADER = '''/* Generated by layer/tests/write_fake_driver_names.py - DO NOT EDIT. */
#include "fake_driver_names.h"

#include <iterator>

namespace {

// The Vulkan functions the fake driver is asked for and does not implement and can be stubbed out
const char *const kUnresolved[] = {
'''

FOOTER = '''};

} // namespace

const std::set<std::string> &fake_expected_unresolved_names() {
    static const std::set<std::string> names(std::begin(kUnresolved), std::end(kUnresolved));
    return names;
}
'''

def collect_logged():
    run = subprocess.run([TESTS], capture_output=True, text=True, cwd=ROOT)
    return {
        line.split("] ", 1)[1].rsplit(" is not implemented", 1)[0]
        for line in run.stderr.splitlines() if line.startswith("[fake driver] ")
    }

def collect_known():
    if not os.path.exists(OUT):
        return set()
    with open(OUT) as f:
        return set(re.findall(r'"(vk[A-Za-z0-9_]+)"', f.read()))

def main():
    if not os.path.exists(TESTS):
        print(f"no test binary at {TESTS}: build it first", file=sys.stderr)
        return 1
    names = sorted(collect_known() | collect_logged())
    if not names:
        print("no names collected (the whitelist is complete?)", file=sys.stderr)
        return 1
    with open(OUT, "w") as f:
        f.write(HEADER)
        f.writelines(f'    "{name}",\n' for name in names)
        f.write(FOOTER)
    print(f"{len(names)} names written to {OUT}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
