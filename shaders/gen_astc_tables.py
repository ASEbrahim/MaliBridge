"""Writes astc_tables.glsl: for each BC7 partition (64 of 2 subsets, then 64 of 3 subsets x the
subset left alone when the other two merge) the ASTC 4x4 two-partition seed whose pattern differs
from it in the fewest texels, as seed << 16 | partition-1 texels (bit y * 4 + x). The ASTC
partition function is the specification's (it matches the 1024 patterns of leegao/etc2_encode's
lut2_packed.bin); BC7's partitions come from bc_tables.glsl (gen_bc_tables.py, from bcdec)."""
import os, re

here = os.path.dirname(os.path.abspath(__file__))
M = 0xffffffff


def hash52(i):
    i ^= i >> 15
    i = (i * 0xEEDE0891) & M
    i ^= i >> 5
    i = (i + (i << 16)) & M
    i ^= i >> 7
    i ^= i >> 3
    i = (i ^ (i << 6)) & M
    i ^= i >> 17
    return i


def select(seed, x, y, z, pc, small):
    if small:
        x, y, z = x << 1, y << 1, z << 1
    seed += (pc - 1) * 1024
    r = hash52(seed)
    s = [(r >> k) & 0xF for k in (0, 4, 8, 12, 16, 20, 24, 28, 18, 22, 26)] + [((r >> 30) | (r << 2)) & 0xF]
    s = [v * v for v in s]
    if seed & 1:
        sh1, sh2 = (4 if seed & 2 else 5), (6 if pc == 3 else 5)
    else:
        sh1, sh2 = (6 if pc == 3 else 5), (4 if seed & 2 else 5)
    sh3 = sh1 if seed & 0x10 else sh2
    s = [v >> k for v, k in zip(s, [sh1, sh2, sh1, sh2, sh1, sh2, sh1, sh2, sh3, sh3, sh3, sh3])]
    a = (s[0] * x + s[1] * y + s[10] * z + (r >> 14)) & 0x3F
    b = (s[2] * x + s[3] * y + s[11] * z + (r >> 10)) & 0x3F
    c = (s[4] * x + s[5] * y + s[8] * z + (r >> 6)) & 0x3F
    d = (s[6] * x + s[7] * y + s[9] * z + (r >> 2)) & 0x3F
    if pc < 4:
        d = 0
    if pc < 3:
        c = 0
    if a >= b and a >= c and a >= d:
        return 0
    if b >= c and b >= d:
        return 1
    return 2 if c >= d else 3


def main():
    src = open(os.path.join(here, 'bc_tables.glsl')).read()

    def table(name):
        m = re.search(r'const uint ' + name + r'\[64\] = uint\[64\]\(([^)]*)\)', src)
        return [int(x.strip().rstrip('u')) for x in m.group(1).split(',')]

    patterns = {}
    for seed in range(1024):
        bits = sum(select(seed, t & 3, t >> 2, 0, 2, True) << t for t in range(16))
        if bits not in (0, 0xffff):
            patterns.setdefault(bits, seed)

    def nearest(labels):
        want = sum(v << t for t, v in enumerate(labels))
        best = min(patterns.items(), key=lambda kv: (min(bin(kv[0] ^ want).count('1'), bin(kv[0] ^ want ^ 0xffff).count('1')), kv[1]))
        return (best[1] << 16) | best[0]

    out = []
    for p in table('BC7_PART2'):
        out.append(nearest([(p >> (2 * t)) & 1 for t in range(16)]))
    for p in table('BC7_PART3'):
        for alone in range(3):
            out.append(nearest([1 if ((p >> (2 * t)) & 3) == alone else 0 for t in range(16)]))
    with open(os.path.join(here, 'astc_tables.glsl'), 'w') as f:
        f.write('/* Generated by shaders/gen_astc_tables.py - do not edit. */\n')
        f.write('const uint ASTC_BC7P[256] = uint[256](\n')
        f.write(',\n'.join('    ' + ', '.join('0x%08xu' % v for v in out[i:i + 8]) for i in range(0, 256, 8)))
        f.write(');\n')
    print('astc_tables.glsl: %d BC7 partitions mapped to ASTC seeds' % len(out))


main()
