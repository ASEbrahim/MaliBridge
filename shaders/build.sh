#!/bin/bash
# Compiles the BCn decoder and transcoder variants into server/bc_spv.h (committed, so a build
# needs no shader compiler). Needs glslangValidator, or glslc (GLSLC=..., else the Android NDK's);
# regenerates bc_tables.glsl and astc_tables.glsl first.
set -eu
cd "$(dirname "$0")"
python3 gen_bc_tables.py
python3 gen_astc_tables.py
out=../server/bc_spv.h
tmp=$(mktemp -d)
glslc=${GLSLC:-}
if ! command -v glslangValidator >/dev/null && [ -z "$glslc" ]; then
  glslc=$(ls "${ANDROID_HOME:-$HOME/Android/Sdk}"/ndk/*/shader-tools/*/glslc 2>/dev/null | tail -1)
fi
{
  echo "/* Generated by shaders/build.sh from bc_decode.comp - do not edit. */"
  echo "#pragma once"
  echo "#include <stdint.h>"
} > "$out"
# variant: name, then defines
variant() {
  local name=$1; shift
  if [ -n "$glslc" ]; then
    "$glslc" -fshader-stage=comp --target-env=vulkan1.1 "$@" -mfmt=c -o "$tmp/$name.h" bc_decode.comp
    { echo "static const uint32_t $name[] = "; cat "$tmp/$name.h"; echo ";"; } >> "$out"
  else
    glslangValidator -V --target-env vulkan1.1 "$@" --vn "$name" -o "$tmp/$name.h" bc_decode.comp >/dev/null
    grep -v '^ *//\|#pragma once' "$tmp/$name.h" | sed 's/^const uint32_t/static const uint32_t/' >> "$out"
  fi
}
for f in BC1 BC2 BC3 BC4 BC5 BC6H BC7; do
  variant spv_$(echo $f | tr A-Z a-z) -DFMT_$f
done
variant spv_bc1_16 -DFMT_BC1 -DPACK16
# transcoders: decode, then encode to a format the GPU samples compressed
variant spv_bc1_etc2 -DFMT_BC1 -DENC_ETC2
variant spv_bc2_astc -DFMT_BC2 -DENC_ASTC
variant spv_bc3_astc -DFMT_BC3 -DENC_ASTC
variant spv_bc4_eac -DFMT_BC4 -DENC_EAC
variant spv_bc5_eac -DFMT_BC5 -DENC_EAC
variant spv_bc7_astc -DFMT_BC7 -DENC_ASTC
variant spv_bc6h_astc -DFMT_BC6H -DENC_ASTC_HDR
# ASTC 6x6 / 8x8 (VKBRIDGE_BC_ASTC_BLOCK): BC2, BC3, BC7
for n in 6 8; do
  for f in BC2 BC3 BC7; do
    variant spv_$(echo $f | tr A-Z a-z)_astc$n -DFMT_$f -DENC_ASTCN -DASTC_N=$n
  done
done
rm -rf "$tmp"
echo "wrote $out"
